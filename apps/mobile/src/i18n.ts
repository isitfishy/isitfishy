/** The languages the app is written in, in the order the settings sheet lists them. */
export const LANGS = ['tr', 'en', 'de', 'es', 'fr', 'it'] as const;
export type Lang = (typeof LANGS)[number];

/** Each language in its own name, so people can find theirs whatever the app is showing. */
export const LANG_NAMES: Record<Lang, string> = {
  tr: 'Türkçe',
  en: 'English',
  de: 'Deutsch',
  es: 'Español',
  fr: 'Français',
  it: 'Italiano',
};

/** The app language for a device language code such as "de" or "fr-CA"; English otherwise. */
export function pickLang(languageCode: string | null | undefined): Lang {
  const code = languageCode?.trim().toLowerCase().split(/[-_]/)[0];
  return LANGS.find((lang) => lang === code) ?? 'en';
}

